    <h2>Problem</h2>
    <p>The Yellow&ndash;Roadway merger had to combine two large LTL technology organizations without forcing customer-facing brands, networks or operating platforms onto one system too early. Separate stacks, development cultures and change-control processes risked service disruption, duplicated work and split governance.</p>
    <h2>What I did</h2>
    <ul>
      <li>Applied one decision filter to every system: customer continuity, complementary vs. duplicate capability, reversibility, evidence from mixed teams, and common governance</li>
      <li>Kept Roadway's in-cab dispatch and Yellow's dock scanning</li>
      <li>Deferred the higher-risk PeopleSoft replacement</li>
      <li>Standardized one Agile SDLC and one change process; production changes went only through the shared process</li>
      <li>Used mixed Yellow/Roadway teams for bounded, evidence-based decisions; people from the non-selected systems helped implement, train and support the selected ones</li>
    </ul>
    <h2>Result</h2>
    <ul class="tr-results">
      <li>$5.4M IT savings, year one</li>
      <li>$8.1M per year after</li>
      <li>$37.8M over five years</li>
    </ul>
    <p>IT became a defined merger synergy line. Company-wide merger savings reached about $100M in year one and a reported $200M annual run rate by early 2006. Sequencing protected customer continuity: management reported no client loss at first. Later network integration reported better service and labor and load productivity, though commercial volume recovery lagged.</p>
