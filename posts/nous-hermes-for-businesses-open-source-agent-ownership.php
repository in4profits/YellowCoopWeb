                <h1>Nous Is Taking Its Open-Source Hermes Agent to Business — Decide Which Parts of Your AI Stack You Own</h1>
                <p class="meta">2026-10-12</p>

                <p>Nous Research, maker of the open-source Hermes Agent, has raised $90 million and is building business editions of the agent. For owners and operators, this makes “own your agent stack” a funded option next to the big walled-garden platforms. It doesn’t mean open source is automatically the right fit for you. Decide what you need to own and what you’re happy to rent.</p>

                <h2>What happened</h2>
                <p>In a note published in October 2026, Nous Research says it raised $90 million (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>). TechCrunch reported on Oct 7, 2026 that the company confirmed the round is a Series B at a $1.5 billion valuation. Robot Ventures led the round, with participation from Nvidia, Union Square Ventures, Menlo Ventures, Samsung, and 1789 Capital. That brings the three-year-old company’s total funding to $158 million (<a href="https://techcrunch.com/2026/10/07/nous-research-confirms-it-hit-1-5b-valuation-launches-ai-agents-for-business-users/">TechCrunch, Oct 7, 2026</a>). In that note, CEO Dillon Rolnick also listed Microsoft’s M12 and Y Combinator among the investors (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>).</p>
                <p>The money funds “Hermes for Businesses,” which TechCrunch describes as letting companies deploy customized AI agents that handle multi-step workflows while keeping their data private and secure (<a href="https://techcrunch.com/2026/10/07/nous-research-confirms-it-hit-1-5b-valuation-launches-ai-agents-for-business-users/">TechCrunch, Oct 7, 2026</a>). SiliconANGLE reports that Nous sells three paid editions. Hermes Cloud is for consumers. Hermes Business and Hermes Enterprise let administrators set team-level token use limits and let users share agent customizations with colleagues (<a href="https://siliconangle.com/2026/10/07/nvidia-samsung-back-90m-round-for-ai-agent-startup-nous-research/">SiliconANGLE, Oct 7, 2026</a>).</p>

                <h2>The numbers, and whose they are</h2>
                <ul>
                    <li><strong>24 million+ clones.</strong> Nous says Hermes has been cloned more than 24 million times (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>). That’s the company’s own figure, repeated by TechCrunch (<a href="https://techcrunch.com/2026/10/07/nous-research-confirms-it-hit-1-5b-valuation-launches-ai-agents-for-business-users/">TechCrunch, Oct 7, 2026</a>).</li>
                    <li><strong>About 2.5% of global AI token usage.</strong> Nous gives this as its “best internal estimate” (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>). It is not an independent measurement.</li>
                    <li><strong>Revenue.</strong> TechCrunch, citing The Wall Street Journal, reports Nous was at roughly $36 million in annualized revenue by mid-September 2026 and expects to pass $100 million before the end of 2026 (<a href="https://techcrunch.com/2026/10/07/nous-research-confirms-it-hit-1-5b-valuation-launches-ai-agents-for-business-users/">TechCrunch, Oct 7, 2026</a>).</li>
                </ul>
                <p>Clone counts measure developer interest. They don’t show that the agent is ready for production in your business.</p>

                <h2>What “owning your intelligence stack” means</h2>
                <p>Rolnick’s note makes the ownership case directly. Nous released Hermes Agent under the MIT license (a permissive open-source license) in February. Rolnick says users “choose where Hermes Agent runs and which models it uses,” and the agent “remembers projects, writes reusable skills as it works, and carries that knowledge across sessions” (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>). He says Hermes for Businesses will let companies “own their own intelligence stacks” and “choose the best models at the best prices” (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>).</p>
                <p>SiliconANGLE adds that Hermes uses a router to send each prompt to the model best suited to it, weighing cost, speed, and output quality. It can use models such as Claude as well as Nous’s own fine-tuned Hermes 4 models (<a href="https://siliconangle.com/2026/10/07/nvidia-samsung-back-90m-round-for-ai-agent-startup-nous-research/">SiliconANGLE, Oct 7, 2026</a>).</p>
                <p>Those are the vendor’s goals and descriptions. The underlying choice is real, though. You can run an agent you control, on infrastructure you choose, with models you can swap. Or you can accept one vendor’s agent, models, and pricing.</p>

                <h2>Build vs buy: questions for owners and operators</h2>
                <h3>1. Where should it run?</h3>
                <p>Self-hosting gives you control over data location and model choice. It also means you own patching, uptime, and security. A vendor-hosted edition moves that work to the vendor. Pick based on how sensitive your data is and how much engineering help you actually have.</p>
                <h3>2. Who controls spend?</h3>
                <p>SiliconANGLE says Hermes Business and Enterprise support team-level token limits (<a href="https://siliconangle.com/2026/10/07/nvidia-samsung-back-90m-round-for-ai-agent-startup-nous-research/">SiliconANGLE, Oct 7, 2026</a>). Whatever platform you choose, set spending caps before rollout, not after the first surprise invoice.</p>
                <h3>3. Who owns the skills?</h3>
                <p>If an agent writes reusable skills, those skills become institutional knowledge. Decide who reviews them, where they’re stored, and what happens to them if you change vendors.</p>
                <h3>4. Can you see what it did?</h3>
                <p>Rolnick argues users “deserve observability” into the agents they rely on (<a href="https://nousresearch.com/a-note-on-our-fundraise">Nous Research, Oct 2026</a>). Hold any agent, open or closed, to that standard: logs, access controls, and a way to review its actions.</p>
                <h3>5. What can it touch?</h3>
                <p>SiliconANGLE notes that Hermes can work with a user’s files, use a browser, and run code in a Docker container (<a href="https://siliconangle.com/2026/10/07/nvidia-samsung-back-90m-round-for-ai-agent-startup-nous-research/">SiliconANGLE, Oct 7, 2026</a>). Powerful access needs clear limits, especially on shared or production machines.</p>

                <h2>The bottom line</h2>
                <p>A well-funded, open-source agent with business editions gives smaller companies a real alternative to lock-in. The hard part isn’t the download. It’s deciding where the agent runs, who pays for its tokens, who owns its skills, and how you’ll watch what it does. If you want a second opinion on what to own and what to buy, Yellow Coop’s <a href="/what-we-do/">fractional CTO and AI services</a> can help you map it out. <a href="/contact/">Start a conversation</a>.</p>
