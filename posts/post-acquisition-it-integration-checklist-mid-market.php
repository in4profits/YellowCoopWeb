                <h1>Post-Acquisition IT Integration: A Day-One Checklist for Mid-Market Owners and Operators</h1>
                <p class="meta">2026-11-06 · By the Yellow Coop Team</p>

                <p>For IT, closing day is the starting gun, not the finish line. You now own the other company’s laptops, logins, contracts, and whatever problems are hiding in them. The short version: before you wire the two networks together, find out what you inherited, decide how much integration the deal really needs, and don’t connect anything you haven’t checked.</p>

                <h2>Integration is not one size</h2>

                <p>Researchers Stefan Henningsson (Copenhagen Business School) and Philip Yetton (University of New South Wales) studied two acquisitions by the same company, Trelleborg Engineered Systems, in a <a href="https://aisel.aisnet.org/cgi/viewcontent.cgi?article=1202&amp;context=icis2011">2011 International Conference on Information Systems paper</a>. Dynaflex (acquired 2004, 50 employees) took three months to integrate. Kléber (acquired 1996, 750 employees) took ten years. The authors trace the gap to starting conditions. Kléber changed the acquirer’s strategy, and porting its systems onto the parent’s ERP platform was estimated at about 1,000 working days, then cancelled as unjustifiable. Dynaflex fit the existing platform.</p>

                <p>Caveats: that is two cases at one company, and the authors say size may have played a minor role. Their advice still travels: where possible, pick targets that are easier and cheaper to integrate. Ours: put an integration line in the deal budget.</p>

                <p>A broader study points the same way. In a <a href="https://pubsonline.informs.org/doi/abs/10.1287/isre.1090.0250">2011 Information Systems Research paper</a>, Hüseyin Tanriverdi (University of Texas at Austin) and Vahap Bülent Uysal (University of Oklahoma) analyzed 141 acquisitions by 86 Fortune 1000 firms. Acquirers with strong cross-business IT integration capability had significantly higher abnormal operating performance in the long run. These are large public companies, and the finding is an association, not a guarantee.</p>

                <h2>Inherited risk is your risk</h2>

                <p>The FTC’s <a href="https://search.ftc.gov/system/files/ftc_gov/pdf/1923022marriottaapc.pdf">analysis of its Marriott consent order</a> shows the downside. According to the FTC’s complaint, a breach of a Starwood reservation database began around July 28, 2014, and went undetected for four years, including the period after Marriott acquired Starwood in September 2016 and took control of its network. The FTC alleges it affected 339 million guest records. Those are allegations, and Marriott is a very different size than you.</p>

                <p>What’s useful is the fix. The FTC’s <a href="https://search.ftc.gov/system/files/ftc_gov/pdf/1923022marriottfinalorder.pdf">final order</a> (December 20, 2024) requires Marriott, after closing an acquisition of an entity handling personal information, to assess that entity’s security program and plan and schedule fixes for the gaps before acquired IT assets enter its production environment. That is a regulator writing a day-one rule. It binds Marriott, not you, but it makes a decent template.</p>

                <h2>The day-one checklist</h2>

                <p>NIST’s <a href="https://nvlpubs.nist.gov/nistpubs/CSWP/NIST.CSWP.29.pdf">Cybersecurity Framework 2.0</a> (February 26, 2024) doesn’t address mergers and acquisitions specifically, but its outcomes read like a punch list.</p>

                <ol>
                    <li><strong>Inventory before you connect.</strong> Hardware, software and cloud services, and supplier contracts with renewal dates (CSF outcomes ID.AM-01, -02, and -04).</li>
                    <li><strong>Find who holds the keys.</strong> Admin accounts, cloud tenants, the domain registrar. If the only person with access is the seller’s IT lead or an outside provider, fix that now (PR.AA-01).</li>
                    <li><strong>Clean up access.</strong> Remove seller staff and former owners who no longer need access, and make sure admins use MFA (PR.AA-05 covers least privilege and regular review).</li>
                    <li><strong>Quarantine, then connect.</strong> Keep the acquired systems on their own network or tenant until the gap list is done, as the Marriott order does in spirit.</li>
                    <li><strong>Get the seller’s support end dates in writing.</strong> Henningsson and Yetton note that when a unit comes from another multi-business organization, the integration contract frequently limits key IT support from the seller’s platform to a maximum of six months. Email, payroll, and ERP may be on a clock.</li>
                    <li><strong>Decide integration system by system.</strong> Dynaflex kept its own production system but moved sales, distribution, and finance onto the parent’s platform. A reasonable rule: merge what leadership needs to see and control, and leave alone what works.</li>
                    <li><strong>Name one owner,</strong> with a date for every item.</li>
                </ol>

                <h2>The takeaway</h2>

                <p>You can’t integrate what you haven’t inventoried, and you shouldn’t plug in what you haven’t checked. Treat the acquired IT as a guest who gets a tour, a badge, and limited access, not the run of the building.</p>

