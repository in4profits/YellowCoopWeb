                <h1>McKinsey Survey: 32% of Respondents Say Their Organization Skipped Buying Software It Could Build With AI — Run the Build-vs-Buy Math Before You Renew</h1>
                <p class="meta">2026-10-11 · By the Yellow Coop Team</p>

                <p><strong>Takeaway:</strong> In McKinsey’s State of AI survey, published in August 2026 (1,719 respondents, fielded May 4 to June 8, 2026), 32% of respondents said their organization had decided against buying at least one software product or feature because it could be built in-house with agentic coding tools. That’s a self-reported purchase decision, not proof that custom builds paid off. Before you cancel a subscription, price the upkeep.</p>

                <h2>What the survey found</h2>
                <p>McKinsey published “The state of AI in 2026: On the road to ROI” on August 25, 2026 (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>; <a href="https://www.linkedin.com/posts/chuimichael_the-state-of-ai-in-2026-on-the-road-to-roi-activity-7497989127586447360-3tZ5">Michael Chui, McKinsey senior fellow and report co-author, LinkedIn, Aug 25, 2026</a>). That’s about seven weeks ago, so it isn’t breaking news, but if you’re planning next year’s software budget, one number in it deserves a hard look.</p>
                <p>The key line: “Nearly a third of respondents (32 percent) report that their organizations have decided against buying one or more software products or features because they could be built internally with agentic coding tools” (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>).</p>
                <p>“Agentic coding tools” are AI assistants that don’t just suggest code but write, run, and fix it across multiple steps with limited supervision.</p>
                <h3>How big is the study, and what does the 32% measure?</h3>
                <ul>
                    <li><strong>Size:</strong> an online survey of 1,719 participants in 97 countries, fielded May 4 to June 8, 2026, with results weighted by each country’s share of global GDP (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>).</li>
                    <li><strong>Who answered this question:</strong> McKinsey asked it only of respondents whose organizations regularly use AI in at least one business function, so the 32% is a share of those respondents (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>).</li>
                    <li><strong>The unit:</strong> “one or more software products or features” (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>). As an analysis by Digital Applied points out, a company that built one dashboard instead of buying a license counts the same as one that replaced a whole platform (<a href="https://www.digitalapplied.com/blog/a-third-of-companies-skipped-buying-software-and-built-it">Digital Applied, Sep 1, 2026</a>).</li>
                    <li><strong>No trend line yet:</strong> the report gives only a 2026 figure for this question, with no prior-year comparison (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>). As of October 2026, this August edition is the latest McKinsey State of AI survey, and we found no newer data on this question.</li>
                    <li><strong>By industry:</strong> respondents in technology (41%) and healthcare payers and providers (39%) reported it most often, while insurance (19%) and the public and social sector (17%) were lowest. Some industry groups are small (as few as 40 insurance respondents), so treat the gaps as rough (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>).</li>
                    <li><strong>By AI maturity:</strong> among AI “high performers” (the roughly 6% of respondents who attribute at least 5% of EBIT to AI and call its impact significant), nearly half reported such a decision, compared with 31% of other respondents (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>).</li>
                </ul>

                <h2>The part that should slow you down</h2>
                <p>The same survey found that 37% of respondents attribute at least some EBIT (earnings before interest and taxes, roughly operating profit) impact to their organization’s AI use, about the same share as last year (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>). It also found that about 20% of respondents said AI-related operating costs, including token costs, constrained their AI use (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>).</p>
                <p>And size matters. Among respondents from organizations with $1 billion or more in revenue, the share reporting that their organization is scaling AI agents rose from 27% last year to 40%; for organizations under that size it stayed essentially flat at 22% (<a href="https://www.mckinsey.com/capabilities/quantumblack/our-insights/the-state-of-ai">McKinsey, Aug 25, 2026</a>). The report doesn’t break the 32% out by company size, and its “smaller” group covers everything under $1 billion in revenue, so a 40-person firm should not assume the same math.</p>

                <h2>A build-vs-buy checklist for owners and operators</h2>
                <h3>Build when…</h3>
                <ul>
                    <li>The tool is narrow and internal (a report, an intake form, a simple workflow).</li>
                    <li>The SaaS product makes you pay for 50 features to use three.</li>
                    <li>Your process is a genuine edge that off-the-shelf tools force you to abandon.</li>
                </ul>
                <h3>Buy (or keep buying) when…</h3>
                <ul>
                    <li>It handles money, payroll, compliance, or customer data at scale.</li>
                    <li>It needs uptime, security patches, and support you can’t staff.</li>
                    <li>The vendor carries certifications your customers or auditors require.</li>
                </ul>
                <h3>Price the whole life, not the first version</h3>
                <p>AI makes the first version cheap. The ongoing costs don’t disappear:</p>
                <ul>
                    <li><strong>Ownership:</strong> who fixes it at 9 p.m. when it breaks?</li>
                    <li><strong>Security:</strong> who reviews AI-written code for access control and secrets handling?</li>
                    <li><strong>Running costs:</strong> hosting plus AI usage fees, which about one in five McKinsey respondents already flag as a constraint.</li>
                    <li><strong>Exit plan:</strong> if the person who built it leaves, can someone else maintain it?</li>
                </ul>
                <h3>Start with one renewal</h3>
                <p>Pick the next subscription coming up for renewal, list what you actually use, and get a rough build estimate that includes a year of maintenance. Compare that, not the sticker price, to the license.</p>

                <h2>The bottom line</h2>
                <p>McKinsey’s number says many organizations now treat building as a real option, not that it’s always the right one. The winners will be the businesses that make the call one tool at a time, with eyes open about upkeep and security.</p>
