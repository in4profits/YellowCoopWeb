                <h1>Test Before You Trust: How Mid-Market Owners and Operators Can Trial an AI Tool on Their Own Work</h1>
                <p class="meta">2026-11-11 · By the Yellow Coop Team</p>

                <p><strong>The takeaway:</strong> Before you buy an AI tool, run it against a few dozen real examples of your own work, scored by the people who do that work today. Demos and benchmark scores can't tell you how a tool handles your documents, your customers, or your edge cases, and the research says the gap can be large.</p>

                <h2>Why demos and benchmarks aren't enough</h2>

                <h3>Vendor accuracy claims can be overstated</h3>

                <p>Stanford researchers ran a preregistered test of more than 200 legal questions through AI research tools after some legal research providers touted their methods as "eliminating" hallucinations or guaranteeing "hallucination-free" citations. <a href="https://onlinelibrary.wiley.com/doi/10.1111/jels.12413">The study</a>, published in the Journal of Empirical Legal Studies (first online April 23, 2025), found that tools from LexisNexis and Thomson Reuters each hallucinated between 17% and 33% of the time. That was better than general-purpose GPT-4, and still far from hallucination-free. The researchers tested the versions available at the time, and these products have changed since, which is exactly the point: test the version you would actually buy.</p>

                <h3>AI helps on some tasks and hurts on others</h3>

                <p>In a preregistered experiment with 758 Boston Consulting Group consultants, <a href="https://www.hbs.edu/faculty/Pages/item.aspx?num=64700">Dell'Acqua and colleagues</a> (first released as Harvard Business School Working Paper 24-013 in September 2023 and since <a href="https://pubsonline.informs.org/doi/10.1287/orsc.2025.21838">published in Organization Science</a>) found that consultants using GPT-4 completed 12.2% more tasks, 25.1% faster, with significantly higher quality across 18 tasks inside the AI's capabilities. On one complex task chosen to sit outside those capabilities, AI users were 19% less likely to produce a correct solution than people working without AI. The authors call this the "jagged technological frontier": AI's strengths and weaknesses don't line up neatly with how hard a task looks. You can't know where the jags fall in your work without trying it on your work.</p>

                <h3>Benchmarks don't transfer neatly</h3>

                <p>NIST's <a href="https://www.nist.gov/publications/artificial-intelligence-risk-management-framework-generative-artificial-intelligence">Generative AI Profile</a> (NIST AI 600-1, July 2024) warns that testing AI with standardized tests designed for humans, like professional licensing exams, "does not guarantee GAI system validity or reliability in those domains," and that gaps between benchmarks and real-world use are likely made worse by "prompt sensitivity." The same document names "confabulation," which it defines as confidently stated but erroneous or false content, as a core generative AI risk.</p>

                <p>And sometimes nobody tests at all. The FTC's <a href="https://search.ftc.gov/system/files/ftc_gov/pdf/2323042_donotpay_complaint.pdf">2024 complaint against DoNotPay</a>, which marketed "the world's first robot lawyer," alleged that its employees had not tested the quality and accuracy of the legal documents and advice generated by most of its law-related features. DoNotPay settled without admitting wrongdoing, <a href="https://www.cnbc.com/2024/09/25/ftc-crackdown-ai-claims-donotpay-companies.html">according to CNBC</a> (September 25, 2024).</p>

                <h2>A six-step trial plan</h2>

                <h3>1. Pick one workflow and define "good"</h3>

                <p>Choose a single job, such as drafting customer replies, summarizing contracts, or coding invoices. Write a sentence or two on what a correct output looks like and what counts as an unacceptable error: a wrong dollar amount, a made-up policy, an invented citation.</p>

                <h3>2. Build a test set from real work</h3>

                <p>Pull a few dozen recent, real examples. Our rule of thumb is 30 to 50, which is a practical starting point, not a research standard. Include the hard ones: messy scans, angry customers, and the exceptions only your best person handles. Mask sensitive data unless your vendor contract and AI use policy allow it. Keep what your team actually did as the answer key.</p>

                <h3>3. Run every candidate on the same set, including "no AI"</h3>

                <p>Use the same inputs and instructions for every tool, and keep your current process as the baseline. Without a baseline you can't tell whether a tool beats what you already have. The BCG study compared AI users against a no-AI group for exactly this reason.</p>

                <h3>4. Have the people who do the work score it blind</h3>

                <p>Score each output as correct, minor edit, major rework, or wrong. Flag any confident falsehood separately. That's the confabulation NIST describes, and it's the costliest error because it looks right. Where you can, hide which tool produced which output so nobody grades their favorite on a curve.</p>

                <h3>5. Time the whole job, not just the AI part</h3>

                <p>Measure minutes from start to finished, including review and fixes. A draft that appears in ten seconds but takes twenty minutes to check may lose to your current process.</p>

                <h3>6. Set the bar before you look, then retest after updates</h3>

                <p>Write the pass rule before you see results, for example: "zero invented facts in customer-facing work, and at least as accurate as our current process." Then rerun the same test set when the vendor ships a major update. The Stanford study found large differences between tools in the same category, so don't assume one good result holds forever.</p>

                <h2>Red flags in vendor conversations</h2>

                <ul>
                    <li>"Hallucination-free" or "100% accurate" with no test method behind it</li>
                    <li>Benchmark scores offered instead of a trial on your examples</li>
                    <li>No way to try the tool on your own data before you sign</li>
                    <li>No answer on what changes when the underlying model is updated</li>
                </ul>

