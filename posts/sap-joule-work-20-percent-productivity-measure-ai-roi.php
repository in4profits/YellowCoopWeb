                <h1>SAP Says Joule Made Its Own Staff 20% More Productive — Measure Your AI Gains Before You Buy the Number</h1>
                <p class="meta">2026-10-07</p>

                <p>At its SAP Connect conference in Las Vegas on October 6, SAP said its new AI interface, Joule Work, is live with 110,000 of its own employees, “with the company seeing 20% productivity gains across finance, HR and procurement” (<a href="https://news.sap.com/2026/10/sap-connect-sap-puts-autonomous-enterprise-to-work/">SAP News Center, October 6, 2026</a>).</p>
                <p>That’s a big, clean number. It’s also a number with no published method behind it.</p>
                <p><strong>The takeaway for operators:</strong> vendor productivity figures are a reason to run a test, not a reason to sign a contract. The only AI gain that matters is the one you measure on your own work, against your own baseline.</p>

                <h2>What SAP actually announced</h2>
                <p>Joule Work is an AI front end for SAP software. Employees ask for things in plain language, and it pulls answers and completes work across SAP and third-party data. Alongside it, <em>Joule Assistants</em> carry out operational steps inside business workflows using existing permissions and audit trails, and SAP says customers control how much autonomy they get (<a href="https://news.sap.com/2026/10/sap-connect-sap-puts-autonomous-enterprise-to-work/">SAP News Center</a>).</p>
                <p>The customer stories are real but early. Novartis describes a newly launched pilot. Peter Wied, Director of Complexity Management at Maschinenfabrik Reinhausen, says work that “once required up to an hour of manual effort” is now “accessible in seconds.” Keith Smith, SAP Platform Architect at CONA Services, says his team looks forward to “exploring and testing Joule’s capabilities in greater depth over the coming months” (<a href="https://news.sap.com/2026/10/sap-connect-sap-puts-autonomous-enterprise-to-work/">SAP News Center</a>).</p>
                <p>Timing is also mixed. CIO reports that general availability of the assistants, Joule Studio, and Joule Work begins this month (<a href="https://www.cio.com/article/4231331/sap-advances-its-autonomous-ai-agenda-with-yet-more-joule-assistants-and-agents.html">CIO, October 6, 2026</a>). Constellation Research notes that much of what was announced lands in SAP’s Early Adopter Care program (its early-access track) in the first quarter of 2027 (<a href="https://www.constellationr.com/insights/news/sap-highlights-its-autonomous-enterprise-joule-agent-vision">Constellation Research, October 6, 2026</a>).</p>

                <h2>What independent voices said</h2>
                <p>The reaction was split, which is healthy.</p>
                <ul>
                    <li><strong>Thomas Randall, research lead at Info-Tech Research Group,</strong> called the announcements “fast-following” rather than a breakthrough, while noting SAP’s real advantage: its systems are already trusted to move money and release orders (<a href="https://www.cio.com/article/4231331/sap-advances-its-autonomous-ai-agenda-with-yet-more-joule-assistants-and-agents.html">CIO</a>).</li>
                    <li><strong>Jason Andersen, principal analyst at Moor Insights &amp; Strategy,</strong> was more upbeat about role-specific agents for areas like procurement and supply chain (<a href="https://www.cio.com/article/4231331/sap-advances-its-autonomous-ai-agenda-with-yet-more-joule-assistants-and-agents.html">CIO</a>).</li>
                    <li><strong>Carmi Levy, an independent technology analyst,</strong> warned of “a wide gap between plans and reality” and said SAP didn’t explain how it handles attacks that trick AI agents with malicious instructions (<a href="https://www.cio.com/article/4231331/sap-advances-its-autonomous-ai-agenda-with-yet-more-joule-assistants-and-agents.html">CIO</a>).</li>
                    <li><strong>Jens Hungershausen, chairman of DSAG, the German-speaking SAP user group,</strong> said there is “still a gap between the vision, the available solutions, and actual customer benefits,” and the group said reliable customer experience with Joule Work is still lacking (<a href="https://www.constellationr.com/insights/news/sap-highlights-its-autonomous-enterprise-joule-agent-vision">Constellation Research</a>).</li>
                </ul>
                <p>When SAP’s own user group says “show us,” that’s your cue too.</p>

                <h2>Why self-reported gains deserve a second look</h2>
                <p>The best-known cautionary tale comes from METR, a nonprofit AI research group. In a 2025 randomized trial, experienced open-source developers took 19% longer on real tasks when allowed to use AI tools, yet afterward still believed AI had sped them up by 20% (<a href="https://metr.org/blog/2025-07-10-early-2025-ai-experienced-os-dev-study/">METR, July 10, 2025</a>).</p>
                <p>To be fair, METR now says those results are out of date for current tools, and it studied software development, not finance or HR. The lesson isn’t “AI makes people slower.” It’s that <strong>how fast work feels and how fast work is can point in opposite directions.</strong> A 20% figure without a method could sit anywhere on that spectrum.</p>

                <h3>How to measure AI productivity on your own team</h3>
                <ol>
                    <li><strong>Pick three to five real workflows.</strong> Choose specific, repeatable tasks: closing a month-end reconciliation, answering a supplier inquiry, building a headcount report. “Finance” is not a workflow.</li>
                    <li><strong>Record a baseline first.</strong> Before anyone touches the tool, measure time per task, error rate, and how often work gets redone. No baseline, no ROI.</li>
                    <li><strong>Count the review time.</strong> If the AI saves 20 minutes and a manager spends 15 checking its output, you saved five. Rework and corrections belong in the math.</li>
                    <li><strong>Run a side-by-side.</strong> Have part of the team use the tool and part work as usual for a few weeks on comparable work. It’s not a lab trial, but it beats a survey.</li>
                    <li><strong>Measure outcomes, not logins.</strong> Adoption counts and “time saved” estimates from the vendor dashboard are activity metrics. Track cycle time, accuracy, and cost per task instead.</li>
                    <li><strong>Ask the vendor for the method.</strong> When you hear “20% productivity gains,” ask: which tasks, measured how, compared to what, and including review time or not?</li>
                </ol>

                <h2>Soft next step</h2>
                <p>SAP may well be onto something, especially for back-office work its systems already run. But a headline number from a vendor’s own deployment is a hypothesis about your business, not a fact about it. <strong>Measure before you scale, and let your own baseline decide.</strong></p>
