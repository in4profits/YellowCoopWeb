                <h1>Can You Copyright AI-Generated Content? A Guide for Mid-Market Owners and Operators</h1>
                <p class="meta">2026-11-07 · By the Yellow Coop Team</p>

                <p><em>This post is practical guidance on U.S. copyright, not legal advice. Talk to counsel before you register, license, or sell anything that matters.</em></p>

                <p>Your marketing team just used AI to make a new logo concept, a product video script, and fifty blog images. Who owns them? Under current U.S. law, the short answer is: you own the parts a human actually authored, and nobody owns the parts the machine decided on its own. That matters the day a competitor copies your campaign, a buyer's lawyers ask what IP you really hold, or you try to register a trademark-worthy design.</p>

                <p>Here's what the rules say and how to set your team up so the valuable stuff stays yours.</p>

                <h2>What the law says right now</h2>

                <h3>Copyright needs a human author</h3>

                <p>On March 18, 2025, the U.S. Court of Appeals for the D.C. Circuit ruled in <a href="https://media.cadc.uscourts.gov/opinions/docs/2025/03/23-5233.pdf"><em>Thaler v. Perlmutter</em></a> that the Copyright Act of 1976 "requires all eligible work to be authored in the first instance by a human being." Computer scientist Stephen Thaler had listed his AI system as the sole author of an image. The court upheld the Copyright Office's refusal to register it. The Supreme Court <a href="https://www.supremecourt.gov/docket/docketfiles/html/public/25-449.html">denied review on March 2, 2026</a>, so that ruling stands.</p>

                <h3>Prompts alone usually aren't enough</h3>

                <p>The U.S. Copyright Office went further in its <a href="https://copyright.gov/ai/Copyright-and-Artificial-Intelligence-Part-2-Copyrightability-Report.pdf">January 29, 2025 report on copyrightability</a> (Part 2 of its AI study, informed by more than 10,000 public comments). Its key conclusions:</p>

                <ul>
                    <li>Using AI to <em>assist</em> human creativity doesn't block copyright protection.</li>
                    <li>Copyright doesn't cover purely AI-generated material, or material where a human lacked enough control over the expressive elements.</li>
                    <li>"Based on the functioning of current generally available technology, prompts do not alone provide sufficient control."</li>
                    <li>Humans can still own their own work that shows up in an AI output, plus their creative selection, arrangement, or modification of the output.</li>
                    <li>Each case is decided individually.</li>
                </ul>

                <p>In plain words: typing "make a bold, modern logo for a plumbing company" doesn't make you the author of what comes back. Redrawing it, combining it with your own artwork, or heavily editing it can create protectable human authorship in those contributions.</p>

                <h3>A real example: the comic book</h3>

                <p>In a <a href="https://www.copyright.gov/docs/zarya-of-the-dawn.pdf">February 21, 2023 letter</a>, the Copyright Office narrowed the registration for <em>Zarya of the Dawn</em>, a comic by Kristina Kashtanova. The Office kept protection for her text and for her selection and arrangement of the images and words, but not for the individual images generated with Midjourney. That's the pattern to expect: the human layer is protected, the raw machine output isn't.</p>

                <h3>Registration means disclosure</h3>

                <p>The Office's <a href="https://www.federalregister.gov/documents/2023/03/16/2023-05321/copyright-registration-guidance-works-containing-material-generated-by-artificial-intelligence">March 16, 2023 registration guidance</a> says applicants "have a duty to disclose" AI-generated content that is more than minimal and to describe what the human contributed. You don't list the AI tool as an author. If you registered something without that disclosure, the guidance explains how to correct the record.</p>

                <h2>What this means for your business</h2>

                <p>The risk isn't that AI content is illegal to use. It's that you may be building brand assets you can't stop others from copying. A few places this bites:</p>

                <ul>
                    <li><strong>Logos and signature designs.</strong> If a central brand image is raw AI output, your copyright claim to it may be thin. (Trademark is a separate question; ask counsel.)</li>
                    <li><strong>Content you sell or license.</strong> Courses, reports, templates, and stock-style images are worth less if anyone can reuse the AI-made parts.</li>
                    <li><strong>Due diligence.</strong> If you're raising money or selling the company, investors or buyers may ask which assets are human-authored. Keep records now so you're not reconstructing them later.</li>
                </ul>

                <h2>A five-step AI content policy</h2>

                <h3>1. Sort content by how much ownership matters</h3>

                <p>Social captions and internal drafts? Use AI freely. Logos, flagship campaigns, product designs, and anything you'll sell or license? Require meaningful human authorship.</p>

                <h3>2. Make humans do the expressive work on high-value assets</h3>

                <p>Use AI for ideas and rough drafts, then have a person write, draw, edit, and arrange the final version. The more the expressive choices are human, the stronger your position under the Office's guidance.</p>

                <h3>3. Keep a simple creation record</h3>

                <p>For high-value pieces, save the prompts, the raw outputs, and the edited final, with who did what. It costs minutes and supports both a registration disclosure and a diligence answer.</p>

                <h3>4. Put it in your contracts</h3>

                <p>Agencies and freelancers may use AI too. Ask them to disclose AI use on deliverables and to confirm which parts are their own human work, alongside the usual ownership transfer language.</p>

                <h3>5. Fold it into your AI use policy</h3>

                <p>This belongs next to your rules on which tools staff may use and what data they can put in. One policy, one owner, reviewed when the law moves.</p>

                <h2>The bottom line</h2>

                <p>AI can speed up creative work without giving away your brand, as long as people still make the choices that matter on the assets you need to own. Decide which content needs human authorship, keep records, and write it into your contracts and AI policy.</p>

