                <h1>ChatGPT Just Got a Meeting Note-Taker With No Bot in the Room — Your Consent Policy Has to Do the Talking</h1>
                <p class="meta">2026-10-07</p>

                <p>On October 6, OpenAI announced a Meetings plugin for the ChatGPT desktop app on Mac. It listens to your calls and in-person conversations, writes a summary, and suggests follow-up tasks it can start for you. There is one design choice every operator should notice: no bot joins the call (<a href="https://www.cultofmac.com/news/chatgpt-for-mac-takes-granola-meeting-notes-action">Cult of Mac, October 6, 2026</a>).</p>
                <p><strong>The takeaway for operators:</strong> when the note-taker is invisible, the only thing telling people they are being recorded is your policy. If you don’t have one, you have a liability with a nice summary attached.</p>

                <h2>What OpenAI actually shipped</h2>
                <p>Here is what OpenAI’s own help article says about the plugin (<a href="https://help.openai.com/en/articles/20001546-the-meetings-plugin-in-chatgpt">OpenAI Help Center, accessed October 7, 2026</a>):</p>
                <ul>
                    <li><strong>Who gets it:</strong> a beta for ChatGPT Pro and Business plans in the macOS desktop app. Enterprise is in a limited alpha. Windows, iOS, and Android are “coming soon.”</li>
                    <li><strong>How it listens:</strong> it uses your microphone plus your Mac’s <em>system audio</em> (whatever your computer is playing, which includes everyone else on a video call). That is why it doesn’t need a bot or a meeting link.</li>
                    <li><strong>What it produces:</strong> a meeting page in ChatGPT Space with your notes, a summary, and suggested action items, enriched with context from apps you’ve connected. You can click to have ChatGPT start an action, such as drafting a follow-up email or updating a project plan.</li>
                    <li><strong>What happens to the audio:</strong> it streams to OpenAI, and once notes are ready it is deleted from your Mac and OpenAI’s servers. If you’re offline or processing stalls, audio can sit on your Mac until it finishes.</li>
                    <li><strong>Who sees the notes:</strong> pages are private by default. If you share one, others see the notes but not the transcript.</li>
                    <li><strong>Limits:</strong> sessions stop after four hours, when you close the laptop lid, or after a long stretch of silence.</li>
                </ul>
                <p>It can also detect when you’re on a call and offer to start taking notes, even if the meeting isn’t on your calendar.</p>

                <h2>The line that matters most</h2>
                <p>OpenAI is unusually blunt about consent. The help article says to “tell everyone in the meeting that you’ll be taking notes from the meeting and get everyone’s consent before you start,” and adds that the reminder in the app “does not notify other participants or obtain their consent for you” (<a href="https://help.openai.com/en/articles/20001546-the-meetings-plugin-in-chatgpt">OpenAI Help Center</a>).</p>
                <p>News9’s technology desk reached the same conclusion: the reminder appears only to the person using the plugin, and workplace policies and local consent rules still apply (<a href="https://www.news9live.com/technology/artificial-intelligence/chatgpt-meetings-beta-pro-business-macos-3013940">News9, October 7, 2026</a>).</p>
                <p>That matters because recording law is not a vibe. California, for example, makes it a crime to record a confidential conversation without the consent of <strong>all</strong> parties, with fines of up to $2,500 per violation, and the law applies to businesses as well as individuals (<a href="https://leginfo.legislature.ca.gov/faces/codes_displaySection.xhtml?lawCode=PEN&amp;sectionNum=632">California Penal Code § 632</a>). Other states and countries have their own rules. Your sales rep in one state calling a prospect in another is exactly the case your lawyer wants to hear about before it happens, not after.</p>

                <h2>Why this is bigger than one plugin</h2>
                <p>Bot-free note-takers are not new, but this one ships inside a tool many of your people already pay for. That changes the adoption pattern. Nobody files an IT ticket. Someone installs a plugin on a Tuesday, and by Friday your board call, a candidate interview, and a customer escalation have all been summarized on a third-party server.</p>
                <p>There is also a second risk that is easy to miss: <strong>action items that act</strong>. A summary that’s slightly wrong is annoying. A follow-up email drafted from a misheard number, sent to a client, is a problem. OpenAI itself tells users to review important details before relying on or sharing the notes.</p>

                <h3>A six-point AI note-taker policy</h3>
                <ol>
                    <li><strong>Decide which tools are approved.</strong> Pick the note-takers your company allows and say so in writing. If you’re on ChatGPT Business, admins can control whether ChatGPT Space and the Meetings plugin are enabled at all, so make that an explicit choice rather than a default.</li>
                    <li><strong>Make the announcement a habit, not a hope.</strong> Require a spoken or written heads-up at the start of every recorded meeting, and put a line in calendar invites. A simple script works: “I’m using an AI note-taker; is everyone OK with that?”</li>
                    <li><strong>Set no-record zones.</strong> Some meetings should never be summarized by AI: HR and performance conversations, legal matters, M&amp;A, and anything covered by a confidentiality agreement that doesn’t allow third-party processing.</li>
                    <li><strong>Know where the notes live and for how long.</strong> Audio may be deleted, but the notes and transcript are still data. Decide who can share meeting pages, with whom, and how long they’re kept.</li>
                    <li><strong>Keep a human between the summary and the send.</strong> Suggested actions are drafts. Nobody should send a client email or change a project plan based on AI notes without reading it first.</li>
                    <li><strong>Treat external calls differently.</strong> Customers, candidates, and partners didn’t sign your AI policy. Ask before recording, and respect a “no.”</li>
                </ol>

                <h2>Soft next step</h2>
                <p>The Meetings plugin looks genuinely useful, and the bot-free design removes a lot of awkwardness. It also removes the one signal that told everyone a machine was listening. <strong>Put that signal back with a clear, short policy before the plugin spreads through your team on its own.</strong></p>
