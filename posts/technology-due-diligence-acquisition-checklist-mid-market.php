                <h1>Technology Due Diligence Before You Buy a Company: A Checklist for Mid-Market Owners and Operators</h1>
                <p class="meta">2026-10-26</p>

                <p><strong>Takeaway:</strong> When you buy a company, you buy its technology: the systems, the contracts, the shortcuts, and possibly an intruder who is already inside. Before closing, get written answers in six areas: systems and contracts, security history, people, data, integration cost, and deal terms. Then keep checking after closing, because the risk doesn’t end at signing.</p>

                <p>Financial due diligence gets a team of accountants. Technology due diligence often gets a one-hour call with the seller’s IT manager. That’s backwards for most modern businesses, where the systems are the operation.</p>

                <h2>Two expensive lessons from big deals</h2>

                <p><strong>Marriott and Starwood.</strong> In 2014, attackers got into the IT systems of Starwood Hotels. Marriott acquired Starwood in 2016 and did not detect the attack until September 2018, according to the UK Information Commissioner’s Office (ICO) <a href="https://ico.org.uk/media2/migrated/2618524/marriott-international-inc-mpn-20201030.pdf">penalty notice of October 30, 2020</a>. Marriott estimated that 339 million guest records were affected, and the ICO fined it £18.4 million.</p>

                <p>Two details matter for buyers. First, Marriott told the ICO it could carry out only limited due diligence on Starwood’s data systems during the acquisition, and the ICO acknowledged there may be circumstances in which in-depth due diligence of a competitor isn’t possible during a takeover. Second, the ICO said a company’s need to conduct due diligence on its data operations “is not time-limited or a ‘one-off’ requirement.” (The fine covered only failures after GDPR took effect in May 2018.) In <a href="https://news.marriott.com/news/2020/10/30/marriott-international-update-on-conclusion-of-uk-ico-investigation-into-starwood-database-security-incident">a statement the same day</a>, Marriott said it would not appeal but made “no admission of liability,” and noted that the incident involved only Starwood’s separate network, which is no longer in use.</p>

                <p><strong>Verizon and Yahoo.</strong> On <a href="https://www.sec.gov/Archives/edgar/data/1011006/000119312517049548/d353690dex991.htm">February 21, 2017</a>, Verizon and Yahoo announced they had cut the price of Verizon’s purchase of Yahoo’s operating business by $350 million and would share certain legal and regulatory liabilities from Yahoo’s data breaches. The Securities and Exchange Commission (SEC) later <a href="https://www.sec.gov/newsroom/press-releases/2018-71">charged Yahoo’s successor, Altaba</a> (April 24, 2018). Its order found that Yahoo’s security team learned of a December 2014 intrusion within days, but investors weren’t told until 2016, as the Verizon deal was closing. Altaba paid a $35 million penalty without admitting or denying the findings.</p>

                <p>You’re probably not buying a hotel chain. But the pattern scales down: the seller’s technology problems become the buyer’s problems on day one.</p>

                <h2>The six-part checklist</h2>

                <h3>1. Systems and contracts</h3>

                <p>Ask for a list of every system the business runs on (ERP, CRM, accounting, line-of-business apps, websites) with an owner, annual cost, and renewal date for each. Flag contracts that can’t transfer to a new owner without vendor consent, accounts or licenses in someone’s personal name, and software on its last supported version.</p>

                <h3>2. Security and incident history</h3>

                <p>Ask in writing: Have you had a breach, ransomware attack, or fraudulent payment in the last five years? Who investigated, and can we see the report? Is multi-factor authentication (a second login step beyond a password) on email, remote access, and admin accounts? When was a backup last restored as a test? Yahoo’s story is why you ask about past incidents directly. Marriott’s is why you also look for a current intruder: where the deal size justifies it, pay for a short compromise assessment before closing.</p>

                <h3>3. People and key-person risk</h3>

                <p>Who actually knows how things work? If the answer is one long-time employee, or an outside contractor holding every admin password, that’s a retention and access problem to solve before closing, not after.</p>

                <h3>4. Data</h3>

                <p>What customer, employee, and payment data does the business hold, where does it live, and what has it promised customers about that data? Those promises come with the data.</p>

                <h3>5. Integration cost</h3>

                <p>Price the work to connect, migrate, or retire systems, plus the technical debt (the shortcuts someone will eventually have to fix). This number can change what the company is worth to you.</p>

                <h3>6. Deal terms</h3>

                <p>Turn findings into terms: specific statements from the seller about security incidents, a holdback or escrow, a price adjustment, or shared liabilities, the same levers Verizon and Yahoo used. Your attorney drafts the language. Your technology review tells them what to ask for.</p>

                <h2>After closing: the first checks</h2>

                <p>The ICO’s point bears repeating: due diligence doesn’t stop at signing. Early on, change shared and admin passwords, remove access for departing staff and vendors, put the acquired company’s email and remote access behind multi-factor authentication, and decide whether its network connects to yours now or only after a security review. The ICO notice also says adequate due diligence would have included reviewing the adequacy of monitoring, including logging, inside the acquired network, so add that to your list.</p>

                <h2>The bottom line</h2>

                <p>Treat technology due diligence like a building inspection: you don’t skip it because the seller seems honest, and you use what you find to negotiate. Yellow Coop’s CTO work includes technology due diligence for acquisitions or investors, and its CISO work includes vendor risk reviews and a written incident response plan. <a href="/contact/">Let’s talk</a>.</p>

