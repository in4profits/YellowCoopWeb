                <h1>How to Measure AI Pilot ROI Before You Scale: A 6-Step Framework for Mid-Market Owners and Operators</h1>
                <p class="meta">2026-10-18</p>

                <p><strong>The takeaway:</strong> An AI pilot that “feels faster” isn’t a business case. Before you scale one into production, measure one unit of work against a baseline and a comparison group, check quality as well as speed, decide in advance where the saved hours will go, and count every cost, including the time people spend checking the AI’s work. Research shows real but uneven gains, and a gap between what people <em>say</em> they saved and what shows up in the numbers.</p>

                <h2>Why pilots look better than production</h2>
                <p>Three findings to keep on your desk:</p>
                <ul>
                    <li><strong>Gains are real but uneven.</strong> In a study of 5,179 customer support agents, access to a generative AI assistant raised issues resolved per hour by 14% on average, with a 34% improvement for novice and low-skilled workers and minimal impact on experienced and highly skilled ones (<a href="https://www.nber.org/papers/w31161">Brynjolfsson, Li, and Raymond, NBER Working Paper 31161</a>; published in <em>The Quarterly Journal of Economics</em>, vol. 140(2), 2025).</li>
                    <li><strong>The same tool can help on one task and hurt on the next.</strong> In a preregistered experiment with 758 knowledge workers, run with Boston Consulting Group, people using GPT-4 completed 12.2% more tasks and finished 25.1% faster on tasks inside the AI’s capabilities. On a task chosen to sit outside them, they were 19% less likely to produce a correct solution (<a href="https://www.hbs.edu/faculty/Pages/item.aspx?num=64700">Dell’Acqua et al., Harvard Business School</a>; published in <em>Organization Science</em>, March 2026, <a href="https://doi.org/10.1287/orsc.2025.21838">doi:10.1287/orsc.2025.21838</a>). The authors call this the “jagged technological frontier.”</li>
                    <li><strong>Feelings are a bad stopwatch.</strong> In a randomized trial with 16 experienced open-source developers, early-2025 AI tools made them take 19% longer per task, yet afterward they believed AI had sped them up by 20% (<a href="https://metr.org/blog/2025-07-10-early-2025-ai-experienced-os-dev-study/">METR, July 10, 2025</a>). It’s a small study, and METR now calls it out of date. Its follow-up with 57 developers points toward speedups, but METR says that data is an unreliable signal because developers who didn’t want to work without AI opted out or held back tasks (<a href="https://metr.org/blog/2026-02-24-uplift-update/">METR, February 24, 2026</a>). The lesson that survives both: measure, don’t poll.</li>
                </ul>

                <h2>Step 1: Pick one unit of work and baseline it</h2>
                <p>Choose something you already count: tickets resolved per hour, invoices processed per day. Pull at least four weeks of data before the pilot starts. If you can’t measure it today, you can’t claim AI improved it tomorrow.</p>

                <h2>Step 2: Keep a comparison group</h2>
                <p>Don’t hand the tool to everyone at once. The support-agent study could isolate the AI’s effect because the tool reached different agents at different times (a “staggered” rollout). Copy that: half the team, or one shift, goes first. Otherwise a busy season gets credit, or blame, that belongs to the AI.</p>

                <h2>Step 3: Measure quality, and split results by person and task</h2>
                <p>Track error rates, rework, or spot-check scores next to speed. Then break results out by experience level and task type. Based on the studies above, expect newer staff and routine tasks to gain the most, and go looking for the task where accuracy quietly drops.</p>

                <h2>Step 4: Decide where the saved hours go</h2>
                <p>This is where most AI ROI cases fall apart. In the Real-Time Population Survey, a nationally representative survey of U.S. adults ages 18 to 64 that economists Alexander Bick, Adam Blandin, and David Deming use to track AI adoption, workers’ self-reported generative AI time savings reached 2.2% of work hours by the second quarter of 2026 (<a href="https://fred.stlouisfed.org/blog/2026/08/does-generative-ai-save-time-at-work">FRED Blog, St. Louis Fed, Aug 27, 2026</a>). The same researchers caution that saved time may go to lower-value tasks or on-the-job leisure instead of more output (<a href="https://www.stlouisfed.org/on-the-economy/2025/nov/state-generative-ai-adoption-2025">St. Louis Fed, Nov 13, 2025</a>).</p>
                <p>Denmark offers a harder look. Economists Anders Humlum and Emilie Vestergaard linked surveys of 25,000 workers at 7,000 workplaces in 11 AI-exposed occupations to government earnings and hours records. 85% of chatbot users said they moved saved time to other job tasks, yet the authors estimate precise null effects on earnings and recorded hours through December 2024, ruling out effects larger than 2% (<a href="https://www.nber.org/papers/w33777">NBER Working Paper 33777, May 2025, revised March 2026</a>). It’s a working paper, not yet peer reviewed, and it measures pay and hours, not output.</p>
                <p>So write it down before the pilot: do freed hours go to a backlog, to absorbing growth without a new hire, or to cutting overtime or contractor spend? If you can’t name the destination, the “savings” is a feeling.</p>

                <h2>Step 5: Count the full cost (a worked example)</h2>
                <p>These numbers are hypothetical, for illustration. Twelve support agents at a loaded cost of $35 an hour work 1,900 hours a year each, or 22,800 hours. The pilot shows 10% more tickets resolved per hour than the comparison group, so the same volume now takes about 20,727 hours. That frees about 2,073 hours, roughly $72,500 of capacity.</p>
                <p>Year-one costs: licenses at $30 per seat per month ($4,320), help desk integration ($15,000), a team lead spending two hours a week reviewing AI output at $50 an hour ($5,200), and four hours of training per agent ($1,680). Total: $26,200.</p>
                <p>Net: about $46,300, but only if the freed capacity replaces a hire, overtime, or outsourced work. If it just turns into slack, the realized return is minus $26,200.</p>

                <h2>Step 6: Set go, fix, or kill rules up front</h2>
                <p>Agree on thresholds before day one. For example: go if throughput rises at least 8% with no rise in errors; fix and re-run if speed improves but quality slips; kill if neither moves after 60 days. Writing the rule first keeps sunk cost out of the decision.</p>

