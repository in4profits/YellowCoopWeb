                <h1>IBM Just Made Bob Self-Hosted — Bring Agentic Dev Tools to the Data, Not the Other Way Around</h1>
                <p class="meta">2026-10-01</p>

                <p>Most AI coding tools still have an unspoken migration plan: send your context to their cloud. On October 1, 2026, IBM flipped that script for IBM Bob — its agentic software development platform — with general availability of a <strong>self-hosted deployment</strong> for on-prem, private cloud, sovereign cloud, and air-gapped environments (<a href="https://www.ibm.com/new/announcements/ibm-bob-expands-to-self-hosted-environments-for-sensitive-and-mission-critical-enterprise-software">IBM announcement</a>; <a href="https://www.prnewswire.com/news-releases/ibm-introduces-self-hosted-deployment-for-ibm-bob-to-help-enterprises-advance-ai-sovereignty-and-governance-302893486.html">PR Newswire</a>).</p>
                <p>If you are an owner or operator in a regulated or IP-heavy shop, this is not an IBM fan letter. It is a reminder that <strong>where the agent runs</strong> belongs in the architecture review — right next to model quality and price.</p>

                <h2>The operator takeaway</h2>
                <p>Stop treating “AI for developers” as a single SaaS checkbox. Split workloads: what can leave the building, what must stay, and who owns the model choice in each lane.</p>
                <p>IBM positions Bob as more than autocomplete: understand, plan, execute, and validate development and modernization work. Self-hosted Bob is meant to keep code, application context, and build artifacts inside customer-managed environments, with support for on-prem models (including air-gapped) or hybrid hooks to approved external model services (<a href="https://www.ibm.com/new/announcements/ibm-bob-expands-to-self-hosted-environments-for-sensitive-and-mission-critical-enterprise-software">IBM announcement</a>).</p>
                <p>Neel Sundaresan, GM of AI and Automation at IBM, put the thesis bluntly: enterprises need AI that operates inside environments they control when the work involves sensitive code and regulated data (<a href="https://www.prnewswire.com/news-releases/ibm-introduces-self-hosted-deployment-for-ibm-bob-to-help-enterprises-advance-ai-sovereignty-and-governance-302893486.html">PR Newswire</a>).</p>

                <h2>Why this lands now</h2>
                <p>IBM’s Institute for Business Value reported that 68% of surveyed executives find meeting data residency and sovereignty requirements across geographies challenging. Futurum Research, cited in IBM’s release, projects hybrid and edge capturing 44% of AI infrastructure by 2030 while public cloud share declines toward 46% in that timeframe (<a href="https://www.prnewswire.com/news-releases/ibm-introduces-self-hosted-deployment-for-ibm-bob-to-help-enterprises-advance-ai-sovereignty-and-governance-302893486.html">PR Newswire</a>).</p>
                <p>You do not need to buy the forecast. You already feel the procurement friction: banks, health, government contractors, and anyone with crown-jewel source code keep asking — “does this tool ship our repo to someone else’s GPU?”</p>
                <p>Self-hosted Bob is IBM’s answer for that objection. Whether Bob is <em>your</em> answer is a separate diligence exercise.</p>

                <h2>What “self-hosted” actually means here</h2>
                <p>At GA, IBM says customers can:</p>
                <ul>
                    <li>Run Bob in customer-managed enterprise environments</li>
                    <li>Keep core Bob capabilities (IDE experience, BobShell, parallel tool calling, agent harness, skills/modes)</li>
                    <li>Choose self-hosted, air-gapped, or hybrid model configurations</li>
                    <li>Bring-your-own-license for supported models</li>
                    <li>Optionally add Premium Packages for Java modernization, IBM i, and IBM Z (<a href="https://www.ibm.com/new/announcements/ibm-bob-expands-to-self-hosted-environments-for-sensitive-and-mission-critical-enterprise-software">IBM announcement</a>)</li>
                </ul>
                <p>Supported self-hosted models at announcement include NVIDIA Nemotron and Poolside Laguna. Hybrid / private SaaS options listed include Claude Sonnet 5.0, Claude Opus 4.8, Gemini 3.7 Flash, and OpenAI GPT 5.6 Sol (<a href="https://www.ibm.com/new/announcements/ibm-bob-expands-to-self-hosted-environments-for-sensitive-and-mission-critical-enterprise-software">IBM announcement</a>).</p>
                <p>Model lists will churn. The durable idea will not: <strong>deployment topology is a first-class feature</strong>, not a security-appendix afterthought.</p>

                <h2>An owner’s checklist before you “just enable coding agents”</h2>

                <h3>1. Classify your repos by blast radius</h3>
                <p>Customer PII paths, payment logic, and unpublished IP should not share a default SaaS agent with marketing microsites. Draw lanes.</p>

                <h3>2. Decide inference location per lane</h3>
                <p>Air-gapped for the crown jewels. Hybrid for less restricted work. IBM’s own example: on-prem models for core banking apps, approved external models for lighter workloads — same developer UX, different trust boundary (<a href="https://www.ibm.com/new/announcements/ibm-bob-expands-to-self-hosted-environments-for-sensitive-and-mission-critical-enterprise-software">IBM announcement</a>).</p>

                <h3>3. Budget for the boring stack</h3>
                <p>Self-hosted AI is not “turn on Bob.” It is GPUs or approved inference hosts, identity, secrets, logging, model updates, and someone who owns uptime. If you have no platform owner, SaaS may still win for non-sensitive work.</p>

                <h3>4. Keep humans on merge and modernization plans</h3>
                <p>Agentic “understand and modernize” is powerful on Java / i / Z estates precisely because those systems are messy. Require review gates for dependency changes and data-touching migrations.</p>

                <h3>5. Ask vendors for topology, not slogans</h3>
                <p>“Enterprise ready” is not a diagram. Demand: where code goes, where embeddings go, what is retained, how air-gap updates work, and what happens when the model provider rotates versions.</p>

                <h2>Build vs buy without the religion</h2>
                <p>Buy a self-hosted agentic platform when you already have regulated or IP-sensitive code blocked from SaaS AI and you can staff the infrastructure. Build thinner wrappers when your need is narrow. Stay on SaaS agents only for code you would be comfortable pasting into a vendor ticket tomorrow.</p>
                <p>Bob is one option in a market productizing sovereignty. Win with a written topology policy — not brand loyalty.</p>

